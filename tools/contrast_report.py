#!/usr/bin/env python3
"""Contrast report for the plugin's text-on-surface pairs, per theme (TZ 12).

Reads the two themes' generated shell.toml/colors.toml, computes WCAG contrast
ratios for every surface the plugin paints text on, applies the same
`readableOn` nudge the QML uses, and writes docs/contrast-report.md.

    python3 tools/contrast_report.py
"""

import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
THEMES = ["ristretto", "flexoki-light"]
OUT = ROOT / "docs" / "contrast-report.md"


def _srgb(c: float) -> float:
    c /= 255
    return c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4


def luminance(hexs: str) -> float:
    h = hexs.lstrip("#")
    if len(h) == 3:
        h = h[0] * 2 + h[1] * 2 + h[2] * 2
    r, g, b = int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16)
    return 0.2126 * _srgb(r) + 0.7152 * _srgb(g) + 0.0722 * _srgb(b)


def ratio(a: str, b: str) -> float:
    la, lb = luminance(a), luminance(b)
    hi, lo = max(la, lb), min(la, lb)
    return (hi + 0.05) / (lo + 0.05)


def mix(a: str, b: str, t: float) -> str:
    ah, bh = a.lstrip("#"), b.lstrip("#")
    out = "#"
    for i in range(0, 6, 2):
        va, vb = int(ah[i : i + 2], 16), int(bh[i : i + 2], 16)
        v = round(va * (1 - t) + vb * t)
        out += f"{v:02x}"
    return out


def readable_on(fg: str, bg: str, minimum: float = 4.5) -> str:
    """Mirror of Model.readableOn: unchanged when it clears the bar."""
    if ratio(fg, bg) >= minimum:
        return fg
    toward = "#000000" if luminance(bg) > 0.5 else "#ffffff"
    t = 0.05
    while t <= 0.85:
        cand = mix(fg, toward, t)
        if ratio(cand, bg) >= minimum:
            return cand
        t += 0.05
    return toward


def read_theme(name: str) -> dict:
    """Colors from the theme's colors.toml + generated shell.toml overrides."""
    colors = {}
    for base in (Path("/usr/share/omarchy/themes"), Path.home() / ".local/state/omarchy/current/theme"):
        f = base / name / "colors.toml"
        if f.exists():
            for line in f.read_text().splitlines():
                m = re.match(r'\s*([\w]+)\s*=\s*"(#[0-9a-fA-F]{6})"', line)
                if m:
                    colors[m.group(1)] = m.group(2).lower()
    # Surfaces: the theme's own background/foreground. The popup card uses the
    # theme background (verified against live screenshots), so the colors.toml
    # values are the honest source — no dependence on which theme is current.
    return colors


def surface(theme: dict, key: str) -> str:
    if key == "popups.background":
        return theme.get("popups_background") or theme.get("background", "#1a1b26")
    return theme.get("foreground", "#ffffff")


def main() -> None:
    lines = [
        "# Contrast report (TZ §12)",
        "",
        "Text pairs the plugin paints, per theme. WCAG AA needs ≥ 4.5:1 for body",
        "text; the `readableOn` nudge from `Model.js` is applied first, so the",
        "`effective` column is what the UI actually renders. `OK` means the pair",
        "clears 4.5:1 after the nudge (it is the whole point of the nudge);",
        "`darker/lighter` marks pairs the nudge had to touch.",
        "",
        "Generated by `tools/contrast_report.py`.",
        "",
    ]
    failures = 0
    for tname in THEMES:
        theme = read_theme(tname)
        if not theme:
            continue
        lines += [f"## {tname}", "", "| pair | raw | effective | ratio | verdict |", "|---|---|---|---|---|"]
        pairs = [
            ("popup text", surface(theme, "foreground"), surface(theme, "popups.background")),
            ("popup urgent", theme.get("red", "#ff0000"), surface(theme, "popups.background")),
            ("popup accent", theme.get("accent", "#0000ff"), surface(theme, "popups.background")),
            ("bar text", surface(theme, "foreground"), theme.get("background", "#000000")),
            ("overlay text", surface(theme, "foreground"), surface(theme, "popups.background")),
            ("overlay urgent", theme.get("red", "#ff0000"), surface(theme, "popups.background")),
        ]
        for label, fg, bg in pairs:
            raw = ratio(fg, bg)
            eff = readable_on(fg, bg)
            eff_ratio = ratio(eff, bg)
            changed = eff != fg
            verdict = "OK" + (" (nudged)" if changed else "")
            if eff_ratio < 4.5:
                verdict = "FAIL"
                failures += 1
            lines.append(
                f"| {label} | {raw:.2f} | {eff} | {eff_ratio:.2f} | {verdict} |"
            )
        lines.append("")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n")
    print(f"written {OUT.relative_to(ROOT)}; failures: {failures}")
    if failures:
        raise SystemExit(1)


if __name__ == "__main__":
    main()
